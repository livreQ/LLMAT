import os
import openai
import json
import numpy as np
import time


class PromptClusterMultiObj(object):

    def __init__(self, data_name, molecule_col, obj_cols):
        """
        Initialize multi-objective prompt clustering.

        Args:
            data_name: Name of the dataset (e.g., 'redox-mer', 'laser')
            molecule_col: Column name for molecules (usually 'SMILES')
            obj_cols: List of objective column names (e.g., ['Ered', 'Gsol'])
        """
        self.data_name = data_name
        self.molecule_col = molecule_col
        self.obj_cols = obj_cols
        self.n_objectives = len(obj_cols)

    def set_api_key(self, api_key=None):
        """
        Sets the OpenAI API key using environment variable.

        Parameters:
        - api_key (str): Your OpenAI API key.
        """
        os.environ["OPENAI_API_KEY"] = api_key
        os.system(f"echo $OPENAI_API_KEY")

    def query_gpt(self, prompt, model="gpt-4o", temperature=0.7, max_tokens=100):
        """
        Sends a prompt to ChatGPT and returns the response.

        Parameters:
        - prompt (str): The input prompt to send to GPT.
        - model (str): The GPT model to use (default: "gpt-4o").
        - temperature (float): Sampling temperature for output diversity (default: 0.7).
        - max_tokens (int): Maximum number of tokens in the response (default: 100).

        Returns:
        - str: The response generated by GPT.
        """
        try:
            # Set API key from environment variable if available
            openai.api_key = os.getenv('OPENAI_API_KEY')

            # Send the request to OpenAI API
            response = openai.ChatCompletion.create(
                model=model,
                messages=[{
                    "role": "user",
                    "content": prompt
                }],
                temperature=temperature,
                max_tokens=max_tokens,
            )

            # Extract the text from the response
            reply = response['choices'][0]['message']['content']
            return reply.strip()

        except Exception as e:
            print(f"Error: {e}")
            return None

    def get_prefix_prompt(self):
        """
        Get the clustering prompt prefix based on dataset and objectives.
        For multi-objective tasks, we use a single prompt that considers both objectives together.
        """

        # Multi-objective redox-mer: Ered and Gsol together
        redox_multiobj_prefix = """You are a chemist. Please use the molecules provided and group them into five clusters (0 to 4) based on their combined performance across TWO objectives: redox potential (Ered) and solvation energy (Gsol).

For each molecule, evaluate:

**Objective 1 - Redox Potential (Ered - to be minimized):**
- Number and type of electron-withdrawing groups (e.g., CF₃, NO₂, CN, halogens)
- Number and type of electron-donating groups (e.g., alkyl, methoxy, hydroxyl)
- Positioning of substituents on aromatic rings (meta, para, ortho)
- Presence of sulfur-containing functional groups (e.g., SCF₃, S=O)
- Degree of molecular polarity (based on F, O, or N atoms)

**Objective 2 - Solvation Energy (Gsol - to be minimized):**
- Polarity and hydrogen bonding capability
- Molecular size and surface area
- Number and type of charged/ionizable groups
- Hydrophilic/hydrophobic balance

**Clustering criteria (considering both objectives):**
- Cluster 0: Poor on both objectives (high Ered, high Gsol)
- Cluster 1: Poor on one objective, moderate on the other
- Cluster 2: Moderate on both objectives
- Cluster 3: Good on one objective, moderate on the other
- Cluster 4: Excellent on both objectives (low Ered, low Gsol)

Consider the trade-offs between these two objectives and assign clusters based on overall multi-objective performance."""

        # Multi-objective laser: Fluorescence Oscillator Strength and Electronic Gap together
        laser_multiobj_prefix = """Act as a computational chemist with expertise in photophysics. Group these SMILES strings into 5 clusters (0 to 4) based on their combined performance across TWO objectives: fluorescence oscillator strength and electronic gap.

For each molecule, evaluate:

**Objective 1 - Fluorescence Oscillator Strength (to be maximized):**
- Conjugation length: Longer conjugation increases oscillator strength
- Aromaticity: Aromatic systems often have strong π-π* transitions
- Functional groups: Electron-donating/withdrawing groups alter oscillator strength
- Molecular rigidity: Rigid molecules tend to have higher oscillator strength

**Objective 2 - Electronic Gap (HOMO-LUMO gap - to be maximized):**
- Conjugation length: Longer conjugation decreases the gap
- Aromaticity: More aromatic systems typically have smaller gaps
- Donor-acceptor character: Push-pull systems decrease the gap
- Molecular planarity: Planar molecules tend to have smaller gaps

**Clustering criteria (considering both objectives):**
- Cluster 0: Poor on both objectives (low oscillator strength, small gap)
- Cluster 1: Poor on one objective, moderate on the other
- Cluster 2: Moderate on both objectives
- Cluster 3: Good on one objective, moderate on the other
- Cluster 4: Excellent on both objectives (high oscillator strength, large gap)

Consider the trade-offs between these two objectives. Note that some features (like conjugation) have opposite effects on the two objectives, creating interesting trade-offs. Assign clusters based on overall multi-objective performance."""

        # Return appropriate prefix based on dataset
        if 'redox-mer' in self.data_name:
            return redox_multiobj_prefix
        elif 'laser' in self.data_name:
            return laser_multiobj_prefix
        else:
            # Default: return empty string
            return ""

    def gpt_clustering_single_objective(self, dataset, obj_col, prefix, cluster_col_name):
        """
        Perform GPT clustering for a single objective.

        Args:
            dataset: Pandas DataFrame
            obj_col: Objective column name
            prefix: Prompt prefix for this objective
            cluster_col_name: Name for the cluster column to create

        Returns:
            Updated dataset with cluster labels
        """
        print(f"\nClustering for objective: {obj_col}")
        print(f"Cluster column: {cluster_col_name}")

        molecules = dataset[self.molecule_col].to_list()
        batch_size = 200
        n_batches = int(np.ceil(len(molecules) / float(batch_size)))

        folder_path = f"benchmarks/MAT/data/llm_clustering_multiobj/{self.data_name}/{obj_col.replace(' ', '_')}/"

        cluster_labels = []
        mole_cluster_dict = {}

        for i in range(n_batches):
            if i == n_batches - 1:
                batch_mole = molecules[i * batch_size:]
            else:
                batch_mole = molecules[i * batch_size:(i + 1) * batch_size]

            formatted_data = "\n".join([f"{j+1}. {item}" for j, item in enumerate(batch_mole)])
            prompt = prefix + f"\n\n**Respond strictly with the counter and numerical cluster labels only. Do not include any additional text.**\nNow please cluster the following molecules:\n{formatted_data}\n"

            delay = 10.0
            result_file = folder_path + self.data_name + "_" + obj_col.replace(' ', '_') + "_" + str(i) + "_result.npy"

            if os.path.exists(result_file):
                print(f"Batch {i} already processed, loading from file...")
                results = np.load(result_file, allow_pickle=True)
            else:
                print(f"Processing batch {i}/{n_batches-1}")
                try:
                    time.sleep(delay)
                    response = self.query_gpt(prompt, max_tokens=4000)
                except openai.error.RateLimitError:
                    print(f"Rate limit hit. Waiting for {delay} seconds...")
                    time.sleep(delay)
                    response = self.query_gpt(prompt, max_tokens=4000)

                print(f"Response: {response[:200]}...")  # Print first 200 chars
                labels = response.split("\n")
                results = []

                for j in range(len(batch_mole)):
                    tmp = labels[j].split()
                    if len(tmp) == 1:
                        results.append((batch_mole[j], tmp[0]))
                    else:
                        results.append((batch_mole[j], tmp[1]))

                # Save results
                if not os.path.exists(folder_path):
                    print(f"Folder '{folder_path}' does not exist, creating it...")
                    os.makedirs(folder_path)

                with open(folder_path + self.data_name + "_" + obj_col.replace(' ', '_') + "_" + str(i) + '_data.json', 'w') as f:
                    json.dump(results, f)

                with open(result_file, 'wb') as outfile:
                    np.save(outfile, results)

            # Process results
            for mole, label in results:
                if "-" in str(label):
                    label = str(label).split("-")[1]
                    print(f"Warning: Batch {i}, fixed label format: {label}")

                try:
                    label_int = int(label)
                    if label_int < 0 or label_int > 4:
                        print(f"Warning: Batch {i}, invalid label {label_int}, using random")
                        label_int = np.random.choice([0, 1, 2, 3, 4])
                except ValueError:
                    print(f"Warning: Batch {i}, non-integer label {label}, using random")
                    label_int = np.random.choice([0, 1, 2, 3, 4])

                cluster_labels.append(label_int)
                mole_cluster_dict[mole] = label_int

        # Assign cluster labels to dataset
        for mole in dataset[self.molecule_col].to_list():
            assert mole in mole_cluster_dict, f"Molecule {mole} not found in cluster dict"
            dataset.loc[dataset[self.molecule_col] == mole, cluster_col_name] = mole_cluster_dict[mole]

        assert len(cluster_labels) == len(molecules), f"Cluster labels length {len(cluster_labels)} != molecules length {len(molecules)}"

        return dataset

    def gpt_clustering_multiobj(self, dataset):
        """
        Perform GPT clustering for multi-objective task.
        Uses a single prompt that considers both objectives together.
        Creates a single cluster column 'llm_cluster'.

        Returns:
            Dataset with cluster column added
        """
        print(f"\n{'='*60}")
        print(f"Multi-Objective Clustering for {self.data_name}")
        print(f"Objectives: {self.obj_cols}")
        print(f"{'='*60}\n")

        # Set API key
        api_key = __import__("os").environ["OPENAI_API_KEY"]
        self.set_api_key(api_key=api_key)

        # Get multi-objective prompt
        prefix = self.get_prefix_prompt()

        if not prefix:
            print(f"Warning: No prompt prefix found for dataset {self.data_name}")
            return dataset

        # Perform clustering with combined multi-objective prompt
        molecules = dataset[self.molecule_col].to_list()
        batch_size = 200
        n_batches = int(np.ceil(len(molecules) / float(batch_size)))

        folder_path = f"benchmarks/MAT/data/llm_clustering_multiobj/{self.data_name}/"

        cluster_labels = []
        mole_cluster_dict = {}

        for i in range(n_batches):
            if i == n_batches - 1:
                batch_mole = molecules[i * batch_size:]
            else:
                batch_mole = molecules[i * batch_size:(i + 1) * batch_size]

            formatted_data = "\n".join([f"{j+1}. {item}" for j, item in enumerate(batch_mole)])
            prompt = prefix + f"\n\n**Respond strictly with the counter and numerical cluster labels only (0-4). Do not include any additional text.**\nNow please cluster the following molecules:\n{formatted_data}\n"

            delay = 10.0
            result_file = folder_path + self.data_name + "_multiobj_" + str(i) + "_result.npy"

            if os.path.exists(result_file):
                print(f"Batch {i} already processed, loading from file...")
                results = np.load(result_file, allow_pickle=True)
            else:
                print(f"Processing batch {i}/{n_batches-1}")
                try:
                    time.sleep(delay)
                    response = self.query_gpt(prompt, max_tokens=4000)
                except openai.error.RateLimitError:
                    print(f"Rate limit hit. Waiting for {delay} seconds...")
                    time.sleep(delay)
                    response = self.query_gpt(prompt, max_tokens=4000)

                print(f"Response: {response[:200]}...")  # Print first 200 chars
                labels = response.split("\n")
                results = []

                for j in range(len(batch_mole)):
                    if j >= len(labels):
                        print(f"Warning: Missing label for molecule {j}, using random")
                        results.append((batch_mole[j], np.random.choice([0, 1, 2, 3, 4])))
                        continue

                    tmp = labels[j].split()
                    if len(tmp) == 1:
                        results.append((batch_mole[j], tmp[0]))
                    elif len(tmp) >= 2:
                        results.append((batch_mole[j], tmp[1]))
                    else:
                        results.append((batch_mole[j], np.random.choice([0, 1, 2, 3, 4])))

                # Save results
                if not os.path.exists(folder_path):
                    print(f"Folder '{folder_path}' does not exist, creating it...")
                    os.makedirs(folder_path)

                with open(folder_path + self.data_name + "_multiobj_" + str(i) + '_data.json', 'w') as f:
                    json.dump(results, f)

                with open(result_file, 'wb') as outfile:
                    np.save(outfile, results)

            # Process results
            for mole, label in results:
                if "-" in str(label):
                    label = str(label).split("-")[1]
                    print(f"Warning: Batch {i}, fixed label format: {label}")

                try:
                    label_int = int(label)
                    if label_int < 0 or label_int > 4:
                        print(f"Warning: Batch {i}, invalid label {label_int}, using random")
                        label_int = np.random.choice([0, 1, 2, 3, 4])
                except ValueError:
                    print(f"Warning: Batch {i}, non-integer label {label}, using random")
                    label_int = np.random.choice([0, 1, 2, 3, 4])

                cluster_labels.append(label_int)
                mole_cluster_dict[mole] = label_int

        # Assign cluster labels to dataset
        for mole in dataset[self.molecule_col].to_list():
            assert mole in mole_cluster_dict, f"Molecule {mole} not found in cluster dict"
            dataset.loc[dataset[self.molecule_col] == mole, "llm_cluster"] = mole_cluster_dict[mole]

        assert len(cluster_labels) == len(molecules), f"Cluster labels length {len(cluster_labels)} != molecules length {len(molecules)}"

        print(f"\n{'='*60}")
        print(f"Multi-Objective Clustering Complete!")
        print(f"Created cluster column: llm_cluster")
        print(f"Cluster distribution: {dataset['llm_cluster'].value_counts().to_dict()}")
        print(f"{'='*60}\n")

        return dataset


